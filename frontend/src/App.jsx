import { useCallback, useEffect, useMemo, useState } from "react";
import { DATA_URL } from "./config.js";
import { pickDefaultYear } from "./utils.js";
import BackgroundScene from "./three/BackgroundScene.jsx";
import Header from "./components/Header.jsx";
import Hero from "./components/Hero.jsx";
import Filters from "./components/Filters.jsx";
import SummaryCards from "./components/SummaryCards.jsx";
import SkylineSection from "./components/SkylineSection.jsx";
import CountryTable from "./components/CountryTable.jsx";
import RankBar from "./components/RankBar.jsx";
import TrendLine from "./components/TrendLine.jsx";
import ScatterCard from "./components/ScatterCard.jsx";
import Signals from "./components/Signals.jsx";
import CountryCompare from "./components/CountryCompare.jsx";
import DataQuality from "./components/DataQuality.jsx";
import GroupInfo from "./components/GroupInfo.jsx";
import Footer from "./components/Footer.jsx";
import Reveal from "./components/Reveal.jsx";
import WebGLBoundary from "./components/WebGLBoundary.jsx";
import { LoadingState, ErrorState, SetupState, EmptyDatasetState } from "./components/States.jsx";

// Reads the file generated by the Python pipeline. Returns { status, data? }.
async function fetchDataset() {
  const response = await fetch(DATA_URL, { cache: "no-cache" });
  if (response.status === 404) return { status: "setup" };
  if (!response.ok) throw new Error(`The server answered with HTTP ${response.status}.`);

  const text = await response.text();
  let data;
  try {
    data = JSON.parse(text);
  } catch {
    // When the file does not exist, the Vite dev server answers with the HTML page instead.
    return { status: "setup" };
  }
  if (!data || !Array.isArray(data.records)) {
    throw new Error("The data file does not have the expected structure (no 'records' list).");
  }
  if (data.records.length === 0) return { status: "empty" };
  return { status: "ready", data };
}

export default function App() {
  const [state, setState] = useState({ status: "loading" });

  const load = useCallback(() => {
    setState({ status: "loading" });
    fetchDataset()
      .then(setState)
      .catch((error) => setState({ status: "error", message: error.message }));
  }, []);

  useEffect(() => {
    load();
  }, [load]);

  const ready = state.status === "ready";

  return (
    <>
      <WebGLBoundary>
        <BackgroundScene />
      </WebGLBoundary>

      <div className="page">
        <Header />
        <main>
          <Hero
            metadata={ready ? state.data.metadata : null}
            recordCount={ready ? state.data.records.length : 0}
            countryCount={ready ? new Set(state.data.records.map((r) => r.country_code)).size : 0}
          />
          {state.status === "loading" && <LoadingState />}
          {state.status === "error" && <ErrorState message={state.message} onRetry={load} />}
          {state.status === "setup" && <SetupState />}
          {state.status === "empty" && <EmptyDatasetState />}
          {ready && <Dashboard data={state.data} />}
          <GroupInfo />
        </main>
        <Footer />
      </div>
    </>
  );
}

function Dashboard({ data }) {
  const { records, metadata, pipeline_summary: summary } = data;

  // list of {code, name}, sorted by name
  const countries = useMemo(() => {
    const names = new Map();
    records.forEach((r) => names.set(r.country_code, r.country_name));
    return [...names].map(([code, name]) => ({ code, name })).sort((a, b) => a.name.localeCompare(b.name));
  }, [records]);

  const years = useMemo(() => [...new Set(records.map((r) => r.year))].sort((a, b) => a - b), [records]);

  const [year, setYear] = useState(() => pickDefaultYear(records, years, countries.length));
  const [selectedCodes, setSelectedCodes] = useState(() => countries.map((c) => c.code));

  const selectedSet = useMemo(() => new Set(selectedCodes), [selectedCodes]);
  const rangeRows = useMemo(() => records.filter((r) => selectedSet.has(r.country_code)), [records, selectedSet]);
  const yearRows = useMemo(() => rangeRows.filter((r) => r.year === year), [rangeRows, year]);

  return (
    <div className="dashboard">
      <Filters
        years={years}
        year={year}
        onYearChange={setYear}
        countries={countries}
        selectedCodes={selectedCodes}
        onSelectedChange={setSelectedCodes}
      />

      <SummaryCards metadata={metadata} records={records} countryCount={countries.length} yearRows={yearRows} year={year} />

      <SkylineSection rows={yearRows} year={year} />

      <CountryTable rows={yearRows} year={year} />

      <section id="charts" className="section">
        <div className="container">
          <Reveal>
            <p className="kicker">04 · Charts</p>
            <h2>GDP growth and inflation</h2>
            <p className="section-lead">
              Bars show {year}; lines show all years for the selected countries. Gaps mean the World Bank has no value.
            </p>
          </Reveal>
          <div className="grid-2">
            <Reveal><RankBar rows={yearRows} field="gdp_growth_pct" title={`GDP growth, ${year}`} /></Reveal>
            <Reveal delay={100}><RankBar rows={yearRows} field="inflation_pct" title={`Inflation, ${year}`} /></Reveal>
            <Reveal><TrendLine rows={rangeRows} field="gdp_growth_pct" title="GDP growth over time" countries={countries} selectedCodes={selectedCodes} /></Reveal>
            <Reveal delay={100}><TrendLine rows={rangeRows} field="inflation_pct" title="Inflation over time" countries={countries} selectedCodes={selectedCodes} /></Reveal>
          </div>
        </div>
      </section>

      <ScatterCard yearRows={yearRows} rangeRows={rangeRows} year={year} />

      <Signals rows={yearRows} year={year} />

      <CountryCompare countries={countries} rangeRows={rangeRows} allRecords={records} year={year} selectedCodes={selectedCodes} />

      <DataQuality records={records} metadata={metadata} summary={summary} countryCount={countries.length} />
    </div>
  );
}
